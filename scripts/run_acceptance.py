"""Run the 20 acceptance cases through handle().

Run from the repository root:  python scripts/run_acceptance.py
Writes outputs/acceptance_transcript.md and logs/runs.jsonl (emptied first, exactly 20 lines).
"""
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
os.chdir(ROOT)

os.environ["AGENT_LOG_PATH"] = "logs/runs.jsonl"
os.environ["WEATHER_MODE"] = "stub"
os.environ.pop("SIMULATE_DB_FAILURES", None)

from agent.run_agent import handle, reset_sessions   # noqa: E402

# id, session, question, simulated failures, required status, required intent
CASES = [
    ("A01", "s1", "What was Pune's revenue on 15 May 2026?", 0, "Answered", "lookup"),
    ("A02", "s1", "And the target?", 0, "Answered", "lookup"),
    ("A03", "s1", "How about Mumbai?", 0, "Answered", "lookup"),
    ("A04", "s2", "How is Hyderabad doing?", 0, "Clarification Needed", "lookup"),
    ("A05", "s2", "revenue on 2026-05-15", 0, "Answered", "lookup"),
    ("A06", "s3", "What was Hydrabad's turnover yesterday?", 0, "Answered", "lookup"),
    ("A07", "s4", "Did Pune hit its target on 2026-05-16?", 0, "Drafted", "target_vs_actual"),
    ("A08", "s4", "Did Pune hit its target on 2026-05-20?", 0, "Answered", "target_vs_actual"),
    ("A09", "s4", "Did Mumbai hit its target on 2026-05-21?", 0, "Answered", "target_vs_actual"),
    ("A10", "s5", "Which store had the highest average revenue between 2026-05-01 and 2026-05-31?", 0, "Answered", "comparison"),
    ("A11", "s5", "Which store had the lowest revenue on 2026-06-10?", 0, "Answered", "comparison"),
    ("A12", "s6", "Which stores are below the reorder threshold for Amul Milk?", 0, "Answered", "inventory"),
    ("A13", "s6", "What are customers saying about Hyderabad?", 0, "Answered", "feedback"),
    ("A14", "s7", "What was Pune's profit margin on 2026-05-15?", 0, "Safe Failure", "unsupported_metric"),
    ("A15", "s8", "What is the capital of India?", 0, "Escalated", "out_of_scope"),
    ("A16", "s9", "What was Mumbai's revenue on 2026-07-15?", 0, "Safe Failure", "lookup"),
    ("A17", "s10", "Why is Pune's revenue so low?", 0, "Escalated", "diagnostic"),
    ("A18", "s11", "What was Kolkata's revenue on 2026-05-15?", 0, "Clarification Needed", "lookup"),
    ("A19", "s12", "What was Pune's revenue on 15 May 2026?", 2, "Answered", "lookup"),
    ("A20", "s13", "What was Pune's revenue on 15 May 2026?", 3, "Escalated", "lookup"),
]


def main():
    log = ROOT / "logs" / "runs.jsonl"
    log.parent.mkdir(exist_ok=True)
    log.write_text("")                       # empty first: the file holds exactly one run
    (ROOT / "outputs").mkdir(exist_ok=True)
    reset_sessions()
    lines = ["# Acceptance transcript", "",
             "Generated by `python scripts/run_acceptance.py` (LLM_MODE=mock, WEATHER_MODE=stub).", ""]
    ok = 0
    for cid, sess, q, fails, want_status, want_intent in CASES:
        if fails:
            os.environ["SIMULATE_DB_FAILURES"] = str(fails)
        else:
            os.environ.pop("SIMULATE_DB_FAILURES", None)
        r = handle(q, sess)
        os.environ.pop("SIMULATE_DB_FAILURES", None)
        good = r["status"] == want_status and r["intent"] == want_intent
        ok += good
        lines += [f"## {cid}", "",
                  f"- session: {sess}" + (f" (SIMULATE_DB_FAILURES={fails})" if fails else ""),
                  f"- question: {q}",
                  f"- status: {r['status']}",
                  f"- intent: {r['intent']}",
                  f"- confidence: {r['confidence']}",
                  f"- route: {r['route']}",
                  f"- attempts: {r['attempts']}",
                  f"- answer_text: {r['answer_text']}", ""]
        print(("OK  " if good else "FAIL"), cid, r["status"], r["intent"], "|", r["answer_text"])
    (ROOT / "outputs" / "acceptance_transcript.md").write_text("\n".join(lines))
    print(f"{ok}/{len(CASES)} cases match the required status and intent")


if __name__ == "__main__":
    main()
